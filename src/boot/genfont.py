#!/usr/bin/env python3
"""genfont.py: font.h for splash.c, ASCII 32..126 as GW x GH 8-bit alpha cells from JetBrains Mono (OFL)."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

FONT = Path(__file__).resolve().parents[2] / "local/fonts/JetBrainsMono.ttf"
GW, GH, PX = 16, 30, 26

f = ImageFont.truetype(str(FONT), PX)
f.set_variation_by_axes([600])
_, top, _, _ = f.getbbox("H")
rows = []
for c in range(32, 127):
    im = Image.new("L", (GW, GH), 0)
    ImageDraw.Draw(im).text((GW // 2, -top + 2), chr(c), font=f, fill=255, anchor="mt")
    rows.append(",".join(map(str, im.tobytes())))
out = Path(__file__).with_name("font.h")
out.write_text(f"/* generated by genfont.py */\n#define GW {GW}\n#define GH {GH}\n"
               f"static const unsigned char font[95][GW * GH] = {{\n{{" + "},\n{".join(rows) + "}\n};\n")
print(out, out.stat().st_size)
