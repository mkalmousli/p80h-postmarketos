#!/usr/bin/env python3
"""genfont.py: regenerate font.h for the clock from JetBrains Mono (OFL, local/fonts/JetBrainsMono.ttf, variable
weight): date and battery lines as 8-bit alpha glyphs."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFilter, ImageFont

FONT = Path(__file__).resolve().parents[2] / "local/fonts/JetBrainsMono.ttf"
TEXT = "".join(map(chr, range(32, 127)))
# name, weight, px or cell (w, h) per char, chars, glow px
SETS = (("date", 650, 50, TEXT, 0), ("bat", 700, 40, TEXT, 0))  # digits: vector strokes (gfx.c)


def font(weight: int, px: int):
    f = ImageFont.truetype(str(FONT), px)
    f.set_variation_by_axes([weight])
    return f


def cell(f, ch: str, size: tuple[int, int]) -> Image.Image:
    _, top, _, bot = f.getbbox("0123456789")
    l, _, r, _ = f.getbbox(ch)
    im = Image.new("L", (r - l, bot - top), 0)
    ImageDraw.Draw(im).text((-l, -top), ch, font=f, fill=255)
    ink = im.resize((size[0] * 86 // 100, size[1]), Image.LANCZOS)  # side bearing of 7 % each side
    out = Image.new("L", size, 0)
    out.paste(ink, ((size[0] - ink.width) // 2, 0))
    return out


def glyphs(weight: int, spec, chars: str, glow: int) -> list[str]:
    out = []
    for ch in chars:
        if isinstance(spec, dict):  # stretched cell
            size = spec.get(ch, spec[""])
            im = Image.new("L", (size[0] + 2 * glow, size[1] + 2 * glow), 0)
            im.paste(cell(font(weight, 400), ch, size), (glow, glow))
            adv, pad = size[0], glow
        else:
            f = font(weight, spec)
            asc, desc = f.getmetrics()
            adv, pad = round(f.getlength(ch)), 2
            im = Image.new("L", (adv + 4, asc + desc), 0)
            ImageDraw.Draw(im).text((2, 0), ch, font=f, fill=255)
        halo = f"(const unsigned char[]){{{','.join(map(str, im.filter(ImageFilter.GaussianBlur(glow / 2)).tobytes()))}}}" \
            if glow else "0"
        a = ",".join(map(str, im.tobytes()))
        out.append(f"{{{ord(ch)},{im.width},{im.height},{adv},{pad},{pad if glow else 0},(const unsigned char[]){{{a}}},{halo}}}")
    return out


lines = ["/* generated by genfont.py */",
         "struct glyph { int c, w, h, adv, hpad, vpad; const unsigned char *a, *glow; };"]
for name, weight, spec, chars, glow in SETS:
    lines.append(f"static const struct glyph font_{name}[] = {{\n" + ",\n".join(glyphs(weight, spec, chars, glow)) + "\n};")
    lines.append(f"#define FONT_{name.upper()}_N {len(chars)}")
Path(__file__).with_name("font.h").write_text("\n".join(lines) + "\n")
