#!/usr/bin/env python3
"""genfont.py: regenerate font.h (8-bit alpha glyphs rendered from DejaVu Sans Mono) for the charge screen."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

LATO = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono%s.ttf"
SETS = (("small", "", 30, range(32, 127)), ("big", "-Bold", 170, [ord(c) for c in "0123456789%"]))


def glyphs(weight: str, px: int, codes) -> list[str]:
    f = ImageFont.truetype(LATO % weight, px)
    asc, desc = f.getmetrics()
    out = []
    for c in codes:
        adv = round(f.getlength(chr(c)))
        im = Image.new("L", (adv + 4, asc + desc), 0)
        ImageDraw.Draw(im).text((2, 0), chr(c), font=f, fill=255)
        data = ",".join(map(str, im.tobytes()))
        out.append(f"{{{c},{im.width},{im.height},{adv},(const unsigned char[]){{{data}}}}}")
    return out


lines = ["/* generated by genfont.py */", "struct glyph { int c, w, h, adv; const unsigned char *a; };"]
for name, weight, px, codes in SETS:
    g = glyphs(weight, px, codes)
    lines.append(f"static const struct glyph font_{name}[] = {{\n" + ",\n".join(g) + "\n};")
    lines.append(f"#define FONT_{name.upper()}_N {len(g)}")
Path(__file__).with_name("font.h").write_text("\n".join(lines) + "\n")
